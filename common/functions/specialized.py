def dynamic_portfolio(config: dict) -> ToolResult:
    """Run the copied dynamic-portfolio engine and expose its native outputs."""
    from features.feature04_dynamic_portfolio.page import _run
    from features.feature04_dynamic_portfolio.results import _metric_summary

    result = _run(config)
    summary = _metric_summary(result["nav"], result["annual_turnover"])
    final_weights = result.get("final_weights", {})
    metrics = {
        "기간 수익률": f"{summary.get('기간 수익률', np.nan):.2%}",
        "연환산 수익률": f"{summary.get('연환산 수익률', np.nan):.2%}",
        "연 변동성": f"{summary.get('연 변동성', np.nan):.2%}",
        "최대 낙폭(MDD)": f"{summary.get('최대 낙폭 (MDD)', np.nan):.2%}",
        "최종 평가액": f"{result['values'].iloc[-1]:,.0f} {config.get('currency', '')}".strip(),
        "현재 비중": ", ".join(f"{ticker} {weight:.1%}" for ticker, weight in final_weights.items() if weight > 0),
    }
    series = {
        "포트폴리오": result["nav"],
        "벤치마크": result["benchmark_nav"],
        "동일 비중": result["equal_weight_nav"],
        "낙폭": result["drawdown"],
    }
    return ToolResult(
        "동적 포트폴리오 백테스트",
        metrics,
        series,
        result["history"],
        f"공통 평가기간: {result['common_start'].date()} ~ {result['common_end'].date()}",
    )


def inflation_compass(
    start: dt.date, end: dt.date, initial: float, threshold: float = 2.0,
    growth_window: int = 200, breakeven_window: int = 60,
    asset_window: int = 60, fred_lag: int = 0, execution_lag: int = 0,
    cost_bps: float = 0.0, preset: str = "원문 재현 가정",
) -> ToolResult:
    from features.feature08_inflation.compass import Config, backtest, metrics, signals

    root = Path(__file__).resolve().parents[2] / "features" / "feature08_inflation" / "data"
    price_frame = pd.read_csv(root / "prices.csv", index_col=0, parse_dates=True)
    fred = pd.read_csv(root / "T5YIE.csv", index_col=0, parse_dates=True).iloc[:, 0]
    price_frame.index = pd.DatetimeIndex(price_frame.index).tz_localize(None)
    fred.index = pd.DatetimeIndex(fred.index).tz_localize(None)
    if preset == "원문 재현 가정":
        fred_lag, execution_lag, cost_bps = 0, 0, 0.0
    elif preset == "보수적 검증":
        fred_lag, execution_lag, cost_bps = 1, 1, 10.0
    config = Config(threshold, growth_window, breakeven_window, asset_window, fred_lag, execution_lag, cost_bps)
    signal = signals(price_frame, fred, config)
    nav, spy, events, regimes = backtest(price_frame, signal, start, end, config)
    stat = metrics(nav)
    return ToolResult(
        "인플레이션 나침반",
        {
            "최종 평가액": f"{nav.iloc[-1] * initial:,.0f}",
            "연환산 수익률": f"{stat['CAGR'] * 100:.2f}%",
            "MDD": f"{stat['MaxDD'] * 100:.2f}%",
            "현재 국면": str(regimes.iloc[-1]) if len(regimes) else "-",
            "거래 가정": preset,
        },
        {"나침반": nav * initial, "SPY": spy * initial},
        events.tail(60),
    )


def inflation_audit(frequency: str = "일별") -> ToolResult:
    """Load the reproducible validation matrix generated by run_research.py."""
    path = Path(__file__).resolve().parents[2] / "features" / "feature08_inflation" / "results" / "summary.csv"
    if not path.exists():
        raise ValueError("검증 결과가 없습니다. run_research.py를 먼저 실행해 주세요.")
    frame = pd.read_csv(path)
    key = "daily" if frequency == "일별" else "monthly"
    selected = frame.loc[frame["Frequency"] == key].copy()
    labels = {
        "Original_close": "원문 재현 가정",
        "Trade_next_close": "다음 날 종가 체결",
        "FRED_previous_day": "FRED 하루 지연",
        "Conservative_10bp": "보수적 · 10bp",
        "Conservative_20bp": "보수적 · 20bp",
        "Level_only": "물가 수준만",
        "No_basket": "바스켓 제외",
        "No_FRED": "FRED 제외",
        "SPY": "SPY",
    }
    selected["검증 조건"] = selected["Model"].map(labels).fillna(selected["Model"])
    original = selected.loc[selected["Model"] == "Original_close"]
    metrics = {"위험 측정 주기": frequency, "검증 조건": f"{len(selected)}개"}
    if not original.empty:
        metrics.update(
            {
                "원문 연복리": f"{float(original.iloc[0]['CAGR']):.2%}",
                "원문 MDD": f"{float(original.iloc[0]['MaxDD']):.2%}",
            }
        )
    columns = [
        "검증 조건", "CAGR", "MaxDD", "Volatility", "Sharpe_rf0", "Sortino", "Calmar", "Start", "End"
    ]
    return ToolResult(
        "인플레이션 나침반 검증 결과",
        metrics,
        table=selected[[column for column in columns if column in selected]].reset_index(drop=True),
        note="원문 재현, 거래 지연, 데이터 지연, 거래비용 및 신호 구성 민감도를 비교합니다.",
    )


def dollar_compass(
    start: dt.date, end: dt.date, initial: float, switch_percent: float, fee_percent: float,
    monthly_contribution: float = 0.0,
) -> ToolResult:
    from features.feature09_dollar.page import add_indicators, backtest_switching, load_market_data, max_drawdown

    data = add_indicators(load_market_data())
    curve, switches = backtest_switching(
        data, start, end, initial, monthly_contribution > 0, monthly_contribution,
        switch_percent / 100.0, fee_percent / 100.0,
    )
    if curve.empty:
        raise ValueError("선택한 기간에 환율 자료가 없습니다.")
    value = curve.set_index("date")["total_value"]
    return ToolResult(
        "달러 환율 나침반",
        {
            "최종 평가액": f"{value.iloc[-1]:,.0f}원",
            "수익률": f"{curve.iloc[-1]['return'] * 100:.2f}%",
            "MDD": f"{max_drawdown(value) * 100:.2f}%",
            "환전 횟수": f"{len(switches):,}회",
        },
        {"포트폴리오": value, "원/달러": curve.set_index("date")["usdkrw"]},
        switches.tail(100),
    )


