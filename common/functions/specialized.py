def dollar_comparison(start: dt.date, end: dt.date, first: str, second: str) -> ToolResult:
    from features.feature09_dollar.page import load_comparison_data

    data = load_comparison_data()
    selected = data[
        (data["date"].dt.date >= start) & (data["date"].dt.date <= end)
    ][["date", first, second]].dropna().copy()
    if first == second or len(selected) < 2:
        raise ValueError("서로 다른 두 지표와 충분한 조회 기간을 선택해 주세요.")
    selected = selected.set_index("date")
    normalized = selected.divide(selected.iloc[0]).mul(100)
    return ToolResult(
        "달러 지표 비교",
        {"비교 기간": f"{normalized.index[0].date()} ~ {normalized.index[-1].date()}"},
        {first: normalized[first], second: normalized[second]},
        normalized.reset_index().tail(300),
    )


def financial_dashboard(
    query: str, start_year: int, end_year: int, source: str, quarterly: bool = False,
    start_quarter: int = 1, end_quarter: int = 4,
) -> ToolResult:
    matches = financial_company_search(query, 1, source)
    if not matches:
        raise ValueError("검색어와 일치하는 기업이 없습니다.")
    return financial_dashboard_company(
        matches[0], start_year, end_year, quarterly, start_quarter, end_quarter
    )


def financial_company_search(query: str, limit: int = 20, source: str = "자동") -> list:
    from features.feature10_financial.data_sources import fetch_dart_companies, fetch_sec_companies, search_companies

    dart_key = os.getenv("DART_API_KEY", "").strip()
    sec_agent = os.getenv("SEC_USER_AGENT", "snowball-portfolio-lab contact@example.com").strip()
    if source == "DART":
        if not dart_key:
            raise ValueError("DART_API_KEY 환경변수가 필요합니다.")
        companies = fetch_dart_companies(dart_key)
    elif source == "SEC":
        companies = fetch_sec_companies(sec_agent)
    else:
        companies = []
        if dart_key:
            try:
                companies.extend(fetch_dart_companies(dart_key))
            except Exception:
                pass
        try:
            companies.extend(fetch_sec_companies(sec_agent))
        except Exception:
            pass
    return search_companies(companies, query, limit=limit)


def financial_dashboard_company(
    company, start_year: int, end_year: int, quarterly: bool = False,
    start_quarter: int = 1, end_quarter: int = 4,
) -> ToolResult:
    from features.feature10_financial.financials import load_financials

    dart_key = os.getenv("DART_API_KEY", "").strip()
    sec_agent = os.getenv("SEC_USER_AGENT", "snowball-portfolio-lab contact@example.com").strip()
    frame, unit = load_financials(company, start_year, end_year, quarterly, dart_key, sec_agent)
    if quarterly:
        allowed = {
            f"{year} Q{quarter}"
            for year in range(start_year, end_year + 1)
            for quarter in range(1, 5)
            if (start_year, start_quarter) <= (year, quarter) <= (end_year, end_quarter)
        }
        frame = frame.loc[[label for label in frame.index if label in allowed]]
    if frame.empty:
        raise ValueError("선택한 기간에 표시할 재무정보가 없습니다.")
    latest = frame.dropna(how="all").iloc[-1]
    metrics = {str(label): f"{float(value):,.1f} {unit}" for label, value in latest.dropna().head(4).items()}
    return ToolResult(
        f"{company.name} 재무 대시보드",
        {"기업": company.label, "출처": company.source, **metrics},
        table=frame.reset_index(),
    )


def moving_average(
    ticker: str, start: dt.date, end: dt.date, months: int, initial: float,
    contribution: float = 0.0, contribution_frequency: str = "매월",
    confirmation_count: int = 1, signal_limit_days: int = 5,
) -> ToolResult:
    from features.feature11_moving_average.backtest import run_backtest
    from features.feature11_moving_average.data_loader import load_price_data

    price = load_price_data(ticker, start, end, months)
    output = run_backtest(
        price, start, end, initial, contribution > 0, contribution,
        contribution_frequency, confirmation_count, signal_limit_days,
    )
    metrics = {
        str(key): (
            f"{value:.2f}%" if str(key).lower().endswith("_pct")
            else f"{value * 100:.2f}%" if str(key).lower() == "xirr" and pd.notna(value)
            else f"{value:,.2f}" if isinstance(value, (int, float))
            else str(value)
        )
        for key, value in output.metrics.items()
    }
    return ToolResult(
        "이동평균 투자전략",
        metrics,
        {"포트폴리오": output.daily["portfolio_value"], "종가": output.daily["Close"]},
        output.events.tail(100),
    )


